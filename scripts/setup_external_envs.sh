#!/usr/bin/env bash
# Create every isolated comparison-method environment and its launcher file.
set -euo pipefail

if [[ "${1:-}" == "--help" || "${1:-}" == "-h" ]]; then
  cat <<'EOF'
usage: bash scripts/setup_external_envs.sh

Creates the pinned R, LIGER, MultiMAP, and rc-tSNE environments. The optional
location variables are:

  NE_ALIGNED_R_ROOT          micromamba binary and root (default: ~/.local/opt/ne-aligned-r)
  NE_ALIGNED_MULTIMAP_VENV   MultiMAP venv (default: ~/.venvs/ne-aligned-multimap)
  NE_ALIGNED_LAUNCHER_FILE   generated exports (default: .ne-aligned-env.sh)
  NE_ALIGNED_MICROMAMBA      an existing micromamba executable
  NE_ALIGNED_R_TIMEOUT       per-method R timeout in seconds (default: 14400)

On linux-64 the conda environments are created from the exact package lists in
envs/linux-64/*.lock (no solving); elsewhere from envs/*/environment.yml. Existing
environments are never updated in place: they are reused as they are, and the pinned
R packages are checked. To rebuild, remove them or choose new locations. The script
bootstraps micromamba when it is absent, builds rc-tSNE locally, writes the launcher
exports, and runs the checker.
EOF
  exit 0
fi

if [[ $# -ne 0 ]]; then
  echo "error: unexpected argument: $1 (use --help)" >&2
  exit 2
fi

repo_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
cd "${repo_dir}"

micromamba_version=2.8.1
r_root=${NE_ALIGNED_R_ROOT:-"${HOME}/.local/opt/ne-aligned-r"}
mamba_root=${MAMBA_ROOT_PREFIX:-"${r_root}/mmroot"}
default_micromamba="${r_root}/bin/micromamba"
if [[ -n "${NE_ALIGNED_MICROMAMBA:-}" ]]; then
  micromamba=${NE_ALIGNED_MICROMAMBA}
  if [[ ! -x "${micromamba}" ]]; then
    echo "error: NE_ALIGNED_MICROMAMBA is not executable: ${micromamba}" >&2
    exit 1
  fi
elif [[ -x "${default_micromamba}" ]]; then
  micromamba=${default_micromamba}
elif command -v micromamba >/dev/null 2>&1; then
  micromamba=$(command -v micromamba)
else
  micromamba=${default_micromamba}
fi
multimap_venv=${NE_ALIGNED_MULTIMAP_VENV:-"${HOME}/.venvs/ne-aligned-multimap"}
launcher_file=${NE_ALIGNED_LAUNCHER_FILE:-"${repo_dir}/.ne-aligned-env.sh"}
r_timeout=${NE_ALIGNED_R_TIMEOUT:-14400}

require_command() {
  command -v "$1" >/dev/null 2>&1 || {
    echo "error: required command '$1' is not available" >&2
    exit 1
  }
}

micromamba_platform() {
  case "$(uname -s):$(uname -m)" in
    Linux:x86_64) echo linux-64 ;;
    Linux:aarch64|Linux:arm64) echo linux-aarch64 ;;
    Darwin:x86_64) echo osx-64 ;;
    Darwin:arm64|Darwin:aarch64) echo osx-arm64 ;;
    *)
      echo "error: unsupported micromamba platform: $(uname -s) $(uname -m)" >&2
      exit 1
      ;;
  esac
}

if [[ ! -x "${micromamba}" ]]; then
  require_command curl
  require_command tar
  platform=$(micromamba_platform)
  archive=$(mktemp "${TMPDIR:-/tmp}/ne-aligned-micromamba.XXXXXX.tar.bz2")
  trap 'rm -f "${archive}"' EXIT
  mkdir -p "$(dirname -- "${micromamba}")"
  echo "Installing micromamba for ${platform} under ${r_root}"
  curl -fLsS \
    "https://micro.mamba.pm/api/micromamba/${platform}/${micromamba_version}" \
    -o "${archive}"
  tar -xjf "${archive}" -C "${r_root}" bin/micromamba
fi

require_command uv
export NE_ALIGNED_R_ROOT="${r_root}"
export NE_ALIGNED_MICROMAMBA="${micromamba}"
export MAMBA_ROOT_PREFIX="${mamba_root}"

platform=$(micromamba_platform)

create_mamba_env() {
  local name=$1
  local specification=$2
  local lock="envs/${platform}/${name}.lock"
  if [[ -f "${mamba_root}/envs/${name}/conda-meta/history" ]]; then
    echo "Using existing ${name} as it is (not updated in place)"
  elif [[ -f "${lock}" ]]; then
    echo "Creating ${name} from the exact package list ${lock}"
    "${micromamba}" create -y -n "${name}" --file "${lock}"
  else
    echo "Creating ${name} from ${specification} (no ${platform} lock; packages are solved)"
    "${micromamba}" create -y -f "${specification}"
  fi
}

create_mamba_env rverify envs/r/environment.yml
bash envs/r/install-cran-extras.sh

create_mamba_env liger2 envs/liger/environment.yml
bash envs/liger/install-cran-extras.sh

create_mamba_env rctsne envs/rctsne/environment.yml
bash scripts/setup/build_rctsne.sh

# MultiMAP is its own uv project (envs/multimap/pyproject.toml, uv.lock, .python-version).
multimap_python="${multimap_venv}/bin/python"
echo "Syncing MultiMAP environment at ${multimap_venv} from envs/multimap/uv.lock"
UV_PROJECT_ENVIRONMENT="${multimap_venv}" uv sync --locked --project envs/multimap

rscript_launcher="${micromamba} run -n rverify Rscript"
liger_launcher="${micromamba} run -n liger2 Rscript"
rctsne_binary="${repo_dir}/src/ne_aligned_utils/methods/external/vendor/rctsne/bin/fast_ctsne"

mkdir -p "$(dirname -- "${launcher_file}")"
{
  echo '# Generated by scripts/setup_external_envs.sh; local paths, do not commit.'
  printf 'export MAMBA_ROOT_PREFIX=%q\n' "${mamba_root}"
  printf 'export NE_ALIGNED_RSCRIPT=%q\n' "${rscript_launcher}"
  printf 'export NE_ALIGNED_LIGER_RSCRIPT=%q\n' "${liger_launcher}"
  printf 'export NE_ALIGNED_MULTIMAP_PYTHON=%q\n' "${multimap_python}"
  printf 'export NE_ALIGNED_RCTSNE_BIN=%q\n' "${rctsne_binary}"
  printf 'export NE_ALIGNED_R_TIMEOUT=%q\n' "${r_timeout}"
} > "${launcher_file}"
chmod 600 "${launcher_file}"

export NE_ALIGNED_RSCRIPT="${rscript_launcher}"
export NE_ALIGNED_LIGER_RSCRIPT="${liger_launcher}"
export NE_ALIGNED_MULTIMAP_PYTHON="${multimap_python}"
export NE_ALIGNED_RCTSNE_BIN="${rctsne_binary}"
export NE_ALIGNED_R_TIMEOUT="${r_timeout}"

echo
echo "Launcher variables written to ${launcher_file}"
echo "For future shells: source ${launcher_file}"
echo
uv run --locked python scripts/check_environment.py
